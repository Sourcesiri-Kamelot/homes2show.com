/**
 * Get real estate commission info by state abbreviation
 */
export const getRealEstateCommission = (stateAbbr) => {
  return stateRealEstateCommissions[stateAbbr?.toUpperCase()];
};

/**
 * Get all state abbreviations
 */
export const getAllStates = () => {
  return Object.keys(stateRealEstateCommissions).sort();
};

/**
 * Search for states by name
 */
export const searchStates = (query) => {
  const searchTerm = query.toLowerCase();
  return Object.entries(stateRealEstateCommissions)
    .filter(([abbr, info]) => 
      info.state.toLowerCase().includes(searchTerm) ||
      info.name.toLowerCase().includes(searchTerm) ||
      abbr.toLowerCase().includes(searchTerm)
    )
    .map(([abbr, info]) => ({ ...info, abbreviation: abbr }));
};

export default stateRealEstateCommissions;
